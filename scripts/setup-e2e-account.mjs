#!/usr/bin/env node

import { execSync } from "node:child_process";
import { randomBytes } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const envTestPath = resolve(root, ".env.test");
const envLocalPath = resolve(root, ".env.local");

function applyEnvFile(filePath) {
	if (!existsSync(filePath)) return;

	for (const line of readFileSync(filePath, "utf8").split("\n")) {
		const trimmed = line.trim();
		if (!trimmed || trimmed.startsWith("#")) continue;

		const eq = trimmed.indexOf("=");
		if (eq === -1) continue;

		const key = trimmed.slice(0, eq).trim();
		const value = trimmed
			.slice(eq + 1)
			.trim()
			.replace(/^["']|["']$/g, "");
		if (!(key in process.env)) {
			process.env[key] = value;
		}
	}
}

applyEnvFile(envLocalPath);
applyEnvFile(envTestPath);

function requireApiUrl() {
	const apiUrl = process.env.E2E_API_URL || process.env.VITE_STOAT_API_URL;
	if (!apiUrl) {
		console.error(
			"Missing E2E_API_URL or VITE_STOAT_API_URL. Set it in .env.local or .env.test.",
		);
		process.exit(1);
	}
	return apiUrl.replace(/\/$/, "");
}

function isInviteSpent(status, body) {
	const text = body.toLowerCase();
	return (
		status === 400 &&
		(text.includes("invite") ||
			text.includes("unknown") ||
			text.includes("already"))
	);
}

async function api(apiUrl, path, { method = "GET", token, body } = {}) {
	const response = await fetch(`${apiUrl}${path}`, {
		method,
		headers: {
			"Content-Type": "application/json",
			...(token ? { "X-Session-Token": token } : {}),
		},
		...(body ? { body: JSON.stringify(body) } : {}),
	});

	const text = await response.text();
	return { response, text, json: text ? JSON.parse(text) : null };
}

function createInviteViaSsh() {
	const invite = randomBytes(16).toString("hex");
	execSync(
		`ssh -o BatchMode=yes stoat 'cd ~/stoat && sudo docker compose exec -T database mongosh revolt --quiet --eval "db.account_invites.insertOne({ _id: \\"${invite}\\" })"'`,
		{ stdio: "inherit" },
	);
	return invite;
}

async function registerAccount(apiUrl, { email, password, invite }) {
	const { response, text, json } = await api(apiUrl, "/auth/account/create", {
		method: "POST",
		body: { email, password, invite },
	});
	if (!response.ok && response.status !== 204) {
		const error = new Error(
			`POST /auth/account/create → ${response.status}: ${text}`,
		);
		error.spentInvite = isInviteSpent(response.status, text);
		throw error;
	}
	return json;
}

async function login(apiUrl, { email, password }) {
	const { response, text, json } = await api(apiUrl, "/auth/session/login", {
		method: "POST",
		body: {
			email,
			password,
			friendly_name: "Stoat E2E Setup",
		},
	});
	if (!response.ok) {
		throw new Error(`POST /auth/session/login → ${response.status}: ${text}`);
	}
	if (json.result !== "Success" || !json.token) {
		throw new Error(`Login did not succeed: result=${json.result}`);
	}
	return json;
}

async function completeOnboard(apiUrl, token, username) {
	const candidates = [username, username.replaceAll("_", "")];
	let lastError;
	for (const candidate of candidates) {
		const { response, text } = await api(apiUrl, "/onboard/complete", {
			method: "POST",
			token,
			body: { username: candidate },
		});
		if (response.ok || response.status === 204) return candidate;
		lastError = new Error(
			`POST /onboard/complete → ${response.status}: ${text}`,
		);
	}
	throw lastError;
}

async function createServer(apiUrl, token, name) {
	const { response, text, json } = await api(apiUrl, "/servers/create", {
		method: "POST",
		token,
		body: { name },
	});
	if (!response.ok) {
		throw new Error(`POST /servers/create → ${response.status}: ${text}`);
	}
	const serverId = json?.server?._id;
	const channelId = json?.channels?.[0]?._id;
	if (!serverId || !channelId) {
		throw new Error("Server create returned no server or channel id");
	}
	return { serverId, channelId };
}

function writeEnvTest(values) {
	const env = `# Generated by scripts/setup-e2e-account.mjs — do not commit
E2E_BASE_URL=${values.baseUrl}
E2E_API_URL=${values.apiUrl}
E2E_EMAIL=${values.email}
E2E_PASSWORD=${values.password}
E2E_USERNAME=${values.username}
E2E_SERVER_ID=${values.serverId}
E2E_CHANNEL_ID=${values.channelId}
`;
	writeFileSync(envTestPath, env, "utf8");
}

async function obtainInvite() {
	if (process.env.E2E_INVITE)
		return { invite: process.env.E2E_INVITE, viaSsh: false };
	console.error(
		"Missing E2E_INVITE. Set a spare invite in .env.local or .env.test before SSH-inserting a new one.",
	);
	process.exit(1);
}

async function main() {
	const apiUrl = requireApiUrl();
	const stamp = Date.now();
	const existingEmail = process.env.E2E_EMAIL;
	const existingPassword = process.env.E2E_PASSWORD;
	const existingUsername = process.env.E2E_USERNAME;

	let email = existingEmail;
	let password = existingPassword;
	let username = existingUsername;
	let session;

	if (existingEmail && existingPassword) {
		session = await login(apiUrl, {
			email: existingEmail,
			password: existingPassword,
		});
		username = existingUsername || `test_e2e_${stamp}`;
	} else {
		email = `test_e2e_${stamp}@viniciusrangel.dev`;
		password = `E2eTest-${randomBytes(12).toString("hex")}!`;
		username = `test_e2e_${stamp}`;

		let { invite } = await obtainInvite();
		try {
			await registerAccount(apiUrl, { email, password, invite });
		} catch (error) {
			if (!error.spentInvite) throw error;
			invite = createInviteViaSsh();
			await registerAccount(apiUrl, { email, password, invite });
		}

		session = await login(apiUrl, { email, password });
		username = await completeOnboard(apiUrl, session.token, username);
	}

	const fixtureName = `test_e2e_${stamp}`;
	const created = await createServer(apiUrl, session.token, fixtureName);

	writeEnvTest({
		baseUrl: process.env.E2E_BASE_URL || "http://127.0.0.1:4173",
		apiUrl,
		email,
		password,
		username,
		serverId: created.serverId,
		channelId: created.channelId,
	});

	console.log(`Wrote ${envTestPath}`);
	console.log(`Username: ${username}`);
	console.log(`Server: ${created.serverId}`);
	console.log(`Channel: ${created.channelId}`);
}

main().catch((err) => {
	console.error(err);
	process.exit(1);
});
